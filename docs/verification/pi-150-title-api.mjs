import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {writeFileSync,readFileSync} from 'node:fs';
import {userInfo} from 'node:os';
const root=process.env.PI_TITLE_PACKAGE;
assert.equal(JSON.parse(readFileSync(`${root}/package.json`)).version,'1.5.0');
const cwd=process.env.HOME, agentDir=process.env.PI_CODING_AGENT_DIR;
assert.ok(cwd && cwd !== userInfo().homedir, 'fresh isolated HOME required');
assert.equal(process.cwd(),cwd,'run from disposable HOME');
assert.ok(agentDir?.startsWith(`${cwd}/`),'tool home must be inside disposable HOME');
const {createAgentSession,DefaultResourceLoader,SessionManager,SettingsManager}=await import(pathToFileURL(`${root}/dist/index.js`));
const extension=`${cwd}/title-extension.mjs`;
writeFileSync(extension,`export default function(pi) { let observedName; pi.on('session_info_changed',event=>{observedName=event.name;}); pi.registerTool({name:'title_probe', label:'Title probe',description:'Model-free title API probe',parameters:{type:'object',properties:{}},async execute(){ const before=pi.getSessionName(); pi.setSessionName('Fixture session title'); const after=pi.getSessionName(); return {content:[{type:'text',text:JSON.stringify({before:before??null,after,observedName})}],details:{}}; }}); }`);
const settingsManager=SettingsManager.create(cwd,agentDir);
const loader=new DefaultResourceLoader({cwd,agentDir,settingsManager,noExtensions:true,additionalExtensionPaths:[extension],noSkills:true,noPromptTemplates:true,noThemes:true});
await loader.reload();
const manager=SessionManager.create(cwd,`${cwd}/sessions`);
manager.appendMessage({role:'user',content:[{type:'text',text:'Synthetic session persistence fixture; never sent to a model.'}],timestamp:Date.now()});
const {session,extensionsResult}=await createAgentSession({cwd,agentDir,settingsManager,resourceLoader:loader,sessionManager:manager,noTools:'builtin'});
assert.deepEqual(extensionsResult.errors,[]);
await session.bindExtensions({mode:'rpc'});
const tool=session.extensionRunner.getAllRegisteredTools().find(t=>t.definition.name==='title_probe');
assert.ok(tool);
const result=await tool.definition.execute('probe',{},new AbortController().signal);
assert.deepEqual(JSON.parse(result.content[0].text),{before:null,after:'Fixture session title',observedName:'Fixture session title'});
assert.equal(manager.getSessionName(),'Fixture session title');
assert.equal(session.sessionName,'Fixture session title');
const file=manager.getSessionFile();
session.dispose();
assert.equal(SessionManager.open(file).getSessionName(),'Fixture session title');
console.log(JSON.stringify({version:'1.5.0',setter:'ExtensionAPI.setSessionName(name: string): void',reader:'ExtensionAPI.getSessionName(): string | undefined',sessionReader:'SessionManager.getSessionName()',reopen:'PASS',nativeTitleEvent:'PASS',modelRequests:0,result:'PASS'}));
