/** Dev-only extraction: the installed acon package remains the sole owner of these declarations. */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
import { parseSource } from "./lib/ts-ast.ts";

const NAMES = ["ReviewSelector", "ReviewAnchor", "ReviewThread", "ReviewDoc", "ActionMeta"] as const;
export const ACON_REVIEW_TYPES = new URL("../src/hub/acon-review-contract.d.ts", import.meta.url);
export function generateAconReviewTypes(source: string, version: string): string {
  if (!/^[0-9]+\.[0-9]+\.[0-9]+(?:-[A-Za-z0-9.-]+)?$/.test(version)) throw new Error("invalid acon version; install the exact declared devDependency");
  const file = parseSource("acon-contract.ts", source), declarations: string[] = [];
  for (const name of NAMES) {
    const matches = file.statements.filter((node): node is ts.InterfaceDeclaration | ts.TypeAliasDeclaration =>
      (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) && node.name.text === name);
    if (matches.length !== 1) throw new Error(`acon ${name} declaration changed; inspect the canonical contract before updating the bridge`);
    const node = matches[0]!;
    if (!node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)) throw new Error(`acon ${name} is not exported; inspect the canonical contract`);
    const inspect = (part: ts.Node): void => {
      if (ts.isImportTypeNode(part) || ts.isTypeQueryNode(part) || ts.isTypeReferenceNode(part) && (!ts.isIdentifier(part.typeName) || !NAMES.includes(part.typeName.text as typeof NAMES[number]))) {
        throw new Error(`acon ${name} has an external type dependency; inspect its DOM-free boundary before regenerating`);
      }
      ts.forEachChild(part, inspect);
    };
    inspect(node);
    declarations.push(node.getText(file));
  }
  const body = declarations.join("\n\n") + "\n", digest = createHash("sha256").update(body).digest("hex");
  return `// Generated by scripts/acon-review-types.ts from @staix/agent-console ${version}; do not edit.\n`
    + `// ponytail: acon's contract entry forces DOM globals; delete this bridge and import directly when acon publishes a DOM-free contract entry.\n`
    + `// Canonical declaration SHA-256: ${digest}\n\n` + body;
}
export function installedAconReviewTypes(): string {
  const packageFile = new URL("../node_modules/@staix/agent-console/package.json", import.meta.url);
  const installed = JSON.parse(readFileSync(packageFile, "utf8")) as { version: string };
  const manifest = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")) as { devDependencies: Record<string, string> };
  if (installed.version !== manifest.devDependencies["@staix/agent-console"]) throw new Error("acon package differs from its exact pin; run bun install --frozen-lockfile");
  return generateAconReviewTypes(readFileSync(new URL("src/contract.ts", packageFile), "utf8"), installed.version);
}
if (import.meta.main) {
  const generated = installedAconReviewTypes();
  if (process.argv.slice(2).join(" ") === "--check") {
    if (readFileSync(ACON_REVIEW_TYPES, "utf8") !== generated) throw new Error("acon review type bridge is stale; inspect the canonical contract and run bun scripts/acon-review-types.ts");
    console.log("acon review type bridge: OK");
  } else if (process.argv.length === 2) writeFileSync(ACON_REVIEW_TYPES, generated);
  else throw new Error("usage: bun scripts/acon-review-types.ts [--check]");
}
